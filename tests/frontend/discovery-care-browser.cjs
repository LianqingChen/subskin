async function noOverflow(page, label) {
  const sizes = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
  assert.ok(sizes.scroll <= sizes.width + 1, `${label}: ${JSON.stringify(sizes)}`)
}
